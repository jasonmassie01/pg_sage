// sequenceNoIdentityReason blocks the sequence migration when the finding
// names no sequence: there is nothing to write a script for.
const sequenceNoIdentityReason = "no sequence identity in evidence"

// sequenceCapacityCandidates is the review-only forward-fix script for a
// sequence near its limit (playbooks-03). pg_sage never runs it: the
// candidate is high risk, forward-fix only and offered as a script or PR.
func sequenceCapacityCandidates(f SourceFinding) []ActionCandidate {
	expires := evidenceTime(f).Add(24 * time.Hour)
	c := ActionCandidate{
		ActionType:    "prepare_sequence_capacity_migration",
		RiskTier:      "high",
		Confidence:    findingDiagnosticConfidence,
		ExpiresAt:     &expires,
		OutputModes:   []string{"generate_pr_or_script"},
		RollbackClass: "forward_fix_only",
	}
	object := strings.TrimSpace(f.ObjectIdentifier)
	if object == "" {
		c.BlockedReason = sequenceNoIdentityReason
		c.VerificationPlan = []string{"rerun the analyzer once the sequence is named"}
		return []ActionCandidate{c}
	}
	quoted := sanitize.QuoteQualifiedString(object)
	c.BlockedReason = "direct sequence capacity changes require migration review"
	c.VerificationPlan = []string{
		"run the runway query and follow the step its binding_limit names",
		"rerun the runway query after the migration: binding_limit and remaining_values",
	}
	c.ScriptOutput = &ScriptOutput{
		Filename:        "sequence_capacity_" + sanitizeScriptPart(object) + ".sql",
		MigrationSQL:    sequenceCapacityMigrationSQL(quoted, sequenceRateComment(f.Detail)),
		VerificationSQL: []string{sequenceRunwaySQL(quoted)},
		PRTitle:         "Review sequence capacity migration: " + object,
		PRBody: "Generated from pg_sage finding " + f.ID + ". Step 1 reads the " +
			"sequence's runway and what limits it. Step 2 widens the sequence to " +
			"bigint; its guard refuses while a smallint or integer column taking " +
			"the sequence's values would overflow first. Step 3 lists the online " +
			"widening of that column. " +
			"Sequence exhaustion is forward-fix only and must be reviewed. " +
			sequenceRateSentence(f.Detail),
		RiskLabels: []string{"high", "forward_fix_only", "sequence_exhaustion"},
		Format:     "sql",
	}
	return []ActionCandidate{c}
}

// SequenceCapacityScript is the same review-only script for the sequence
// named schema.name by its catalog names, with detail's runway forecast
// (the DetailRunway* keys and "increment") as Step 1's rate. Sage Review's
// schema-debt generator attaches it to its capacity proposals
// (review-02d); pg_sage never runs it.
func SequenceCapacityScript(sequence string, detail map[string]any) string {
	return sequenceCapacityMigrationSQL(sanitize.QuoteQualifiedString(sequence),
		sequenceRateComment(detail))
}

// sequenceCapacityMigrationSQL takes an already quoted sequence name. The
// name appears only inside quoted identifiers and string literals, never on
// a comment line, where a newline in it would become SQL. rateComment is
// Step 1's rate (sequenceRateComment), built from numbers alone.
func sequenceCapacityMigrationSQL(quotedSequence, rateComment string) string {
	return `-- Forward-fix sequence capacity migration generated by pg_sage.
-- pg_sage never runs this script. Review each step before running it.
-- Step 1 (read-only): the runway. binding_limit names what stops nextval first:
--   sequence: the sequence's type or MAXVALUE (MINVALUE when descending): step 2.
--             A bigint sequence at the bigint limit has no wider type to move to.
--   column:   a smallint or integer column overflows first: step 3, then step 2.
-- owning_column NULL: no column takes the values through OWNED BY, identity or
-- DEFAULT. Check application code that calls nextval before step 2: its guard
-- cannot see such a column. remaining_values NULL: this role cannot read
-- last_value; rerun as the sequence's owner.
` + rateComment + sequenceRunwaySQL(quotedSequence) + `
-- Step 2 (binding_limit = sequence): widen the sequence to bigint. AS bigint
-- moves a default MAXVALUE (MINVALUE) to the bigint limit; a custom one is
-- kept: raise it with ALTER SEQUENCE ... MAXVALUE only if it was not deliberate.
` + sequenceWidenSQL(quotedSequence) + `
` + sequenceColumnWideningSteps
}

// sequenceColumnWideningSteps is the online column widening, as comments:
// it needs the table's key, batch size and foreign keys, which only a
// reviewer can choose.
const sequenceColumnWideningSteps = `
-- Step 3 (binding_limit = column): widen the column online. An in-place
-- ALTER TABLE ... ALTER COLUMN ... TYPE bigint rewrites the table and its indexes
-- under an ACCESS EXCLUSIVE lock for the whole rewrite. Instead, with <table>
-- and <column> from the runway query's owning_table and owning_column:
--   1. ALTER TABLE <table> ADD COLUMN <column>_new bigint;
--   2. Create a trigger that sets NEW.<column>_new := NEW.<column> on INSERT
--      and UPDATE, so new rows are copied while the backfill runs.
--   3. Backfill in batches, committing each: UPDATE <table> SET <column>_new =
--      <column> WHERE <key range> AND <column>_new IS NULL;
--   4. ALTER TABLE <table> ADD CONSTRAINT <column>_new_not_null
--      CHECK (<column>_new IS NOT NULL) NOT VALID;
--   5. ALTER TABLE <table> VALIDATE CONSTRAINT <column>_new_not_null;
--   6. CREATE UNIQUE INDEX CONCURRENTLY on <column>_new when <column> is a key,
--      and widen the columns of foreign keys that reference <column>.
--   7. Swap in one short transaction under SET LOCAL lock_timeout = '5s': drop
--      the trigger, move the identity or DEFAULT nextval and OWNED BY to
--      <column>_new, rename both columns, and swap the primary key USING INDEX.
--   8. Run step 2 (its guard now passes), then rerun the step 1 query.`

// sequenceRunwaySQL reads the sequence from pg_sequences with the
// narrowest integer column that takes its values, and reports the limit
// that binds first and how many values remain toward it. Ascending
// sequences run toward max_value, descending ones toward min_value.
func sequenceRunwaySQL(quotedSequence string) string {
	return `SELECT s.schemaname, s.sequencename, s.data_type::text AS data_type,
       s.last_value, s.min_value, s.max_value, s.increment_by, s.cycle,
       o.owning_table, o.owning_column, o.column_type,
       l.effective_limit,
       CASE WHEN s.last_value IS NOT NULL
                 OR pg_catalog.has_sequence_privilege(c.oid, 'SELECT,USAGE')
            THEN pg_catalog.floor((l.effective_limit - COALESCE(s.last_value::numeric,
                 s.start_value::numeric - s.increment_by)) / s.increment_by)
       END AS remaining_values,
       CASE WHEN l.column_limit = l.effective_limit AND o.type_max < 9223372036854775807
            THEN 'column' ELSE 'sequence' END AS binding_limit
FROM pg_catalog.pg_sequences s
JOIN pg_catalog.pg_namespace n ON n.nspname = s.schemaname
JOIN pg_catalog.pg_class c ON c.relnamespace = n.oid AND c.relname = s.sequencename
LEFT JOIN LATERAL (
    SELECT u.attrelid::pg_catalog.regclass::text AS owning_table,
           u.attname::text AS owning_column,
           pg_catalog.format_type(u.atttypid, u.atttypmod) AS column_type,
           CASE u.atttypid WHEN 'pg_catalog.int2'::pg_catalog.regtype THEN 32767
                WHEN 'pg_catalog.int4'::pg_catalog.regtype THEN 2147483647
                WHEN 'pg_catalog.int8'::pg_catalog.regtype THEN 9223372036854775807
           END::numeric AS type_max,
           CASE u.atttypid WHEN 'pg_catalog.int2'::pg_catalog.regtype THEN -32768
                WHEN 'pg_catalog.int4'::pg_catalog.regtype THEN -2147483648
                WHEN 'pg_catalog.int8'::pg_catalog.regtype THEN -9223372036854775808
           END::numeric AS type_min
    FROM (` + sequenceConsumersSQL(quotedSequence) + `) u
    ORDER BY type_max NULLS LAST, owning_table, owning_column
    LIMIT 1
) o ON true
CROSS JOIN LATERAL (
    SELECT CASE WHEN s.increment_by > 0 THEN o.type_max ELSE o.type_min END AS column_limit,
           CASE WHEN s.increment_by > 0
                THEN LEAST(s.max_value::numeric, COALESCE(o.type_max, s.max_value))
                ELSE GREATEST(s.min_value::numeric, COALESCE(o.type_min, s.min_value))
           END AS effective_limit
) l
WHERE c.oid = ` + sequenceRegclass(quotedSequence) + `;`
}

// sequenceConsumersSQL lists the columns that take the sequence's values:
// owned-by and identity columns (pg_depend 'a' and 'i', as the SRE runway
// probe resolves them) and columns whose DEFAULT calls nextval on it.
func sequenceConsumersSQL(quotedSequence string) string {
	seq := sequenceRegclass(quotedSequence)
	return `SELECT a.attrelid, a.attname, a.atttypid, a.atttypmod
          FROM pg_catalog.pg_depend d
          JOIN pg_catalog.pg_attribute a
            ON a.attrelid = d.refobjid AND a.attnum = d.refobjsubid
          WHERE d.classid = 'pg_catalog.pg_class'::pg_catalog.regclass
            AND d.objid = ` + seq + ` AND d.objsubid = 0
            AND d.refclassid = 'pg_catalog.pg_class'::pg_catalog.regclass
            AND d.refobjsubid > 0 AND d.deptype IN ('a', 'i')
          UNION
          SELECT a.attrelid, a.attname, a.atttypid, a.atttypmod
          FROM pg_catalog.pg_depend d
          JOIN pg_catalog.pg_attrdef ad ON ad.oid = d.objid
          JOIN pg_catalog.pg_attribute a
            ON a.attrelid = ad.adrelid AND a.attnum = ad.adnum
          WHERE d.classid = 'pg_catalog.pg_attrdef'::pg_catalog.regclass
            AND d.refclassid = 'pg_catalog.pg_class'::pg_catalog.regclass
            AND d.refobjid = ` + seq
}

// sequenceWidenSQL is the guarded ALTER SEQUENCE: one DO block that
// refuses while a smallint or integer column taking the sequence's values
// would overflow at or before the sequence's own bound (the runway's
// binding_limit = column: widening the sequence would not help) and
// otherwise alters the sequence under lock_timeout.
func sequenceWidenSQL(quotedSequence string) string {
	body := `
DECLARE
    narrow text;
BEGIN
    SELECT pg_catalog.string_agg(u.attrelid::pg_catalog.regclass::text || '.' ||
               pg_catalog.quote_ident(u.attname) || ' ' ||
               pg_catalog.format_type(u.atttypid, u.atttypmod), ', ')
      INTO narrow
      FROM (` + sequenceConsumersSQL(quotedSequence) + `) u
     WHERE u.atttypid IN ('pg_catalog.int2'::pg_catalog.regtype,
                          'pg_catalog.int4'::pg_catalog.regtype)
       AND EXISTS (
           SELECT 1 FROM pg_catalog.pg_sequence q
            WHERE q.seqrelid = ` + sequenceRegclass(quotedSequence) + `
              AND CASE WHEN q.seqincrement > 0
                       THEN q.seqmax >= CASE WHEN u.atttypid =
                            'pg_catalog.int2'::pg_catalog.regtype THEN 32767 ELSE 2147483647 END
                       ELSE q.seqmin <= CASE WHEN u.atttypid =
                            'pg_catalog.int2'::pg_catalog.regtype THEN -32768 ELSE -2147483648 END
                  END);
    IF narrow IS NOT NULL THEN
        RAISE EXCEPTION 'pg_sage: % takes this sequence''s values; widen it first (step 3)',
            narrow;
    END IF;
    PERFORM pg_catalog.set_config('lock_timeout', '5s', true);
    ALTER SEQUENCE ` + quotedSequence + ` AS bigint;
END
`
	tag := dollarTag(body)
	return "DO " + tag + body + tag + ";"
}

// dollarTag picks a dollar-quote tag that does not occur in body, so a
// sequence name cannot end the quoted block early.
func dollarTag(body string) string {
	tag := "$pg_sage$"
	for i := 1; strings.Contains(body, tag); i++ {
		tag = "$pg_sage_" + strconv.Itoa(i) + "$"
	}
	return tag
}

func sequenceRegclass(quotedSequence string) string {
	return sanitize.QuoteLiteral(quotedSequence) + "::regclass"
}
