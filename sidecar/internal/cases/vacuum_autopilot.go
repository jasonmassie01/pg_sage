func autovacuumTuningCandidate(f SourceFinding) ActionCandidate {
	sql := strings.TrimSpace(f.RecommendedSQL)
	expires := evidenceTime(f).Add(72 * time.Hour)
	candidate := ActionCandidate{
		ActionType:       "set_table_autovacuum",
		RiskTier:         "moderate",
		Confidence:       0.72,
		ProposedSQL:      sql,
		ExpiresAt:        &expires,
		OutputModes:      []string{"queue_for_approval", "generate_pr_or_script"},
		RollbackClass:    "unknown",
		RecoveryDetail:   "The previous table storage parameters have not been captured. Capture which settings were explicit and their values before preparing recovery; RESET may not restore the previous state.",
		VerificationPlan: verificationPlanForAction("set_table_autovacuum"),
	}
	candidate.ScriptOutput = scriptOutputFromFinding(f, candidate)
	if rollback, ok := capturedReloptionRollback(sql, f.RollbackSQL); ok {
		candidate.RollbackClass = "reversible"
		candidate.RecoveryDetail = "The finding captured the table's previous storage " +
			"parameters; the rollback restores them."
		candidate.ScriptOutput.RollbackSQL = rollback
	}
	return candidate
}

// capturedReloptionRollback trusts a finding's rollback (vacuum-07) only
// when it is an ALTER TABLE of the same table as the change.
func capturedReloptionRollback(change, rollback string) (string, bool) {
	rollback = strings.TrimSpace(rollback)
	target, ok := alterTableTarget(change)
	if !ok || rollback == "" {
		return "", false
	}
	if other, ok := alterTableTarget(rollback); !ok || other != target {
		return "", false
	}
	return rollback, true
}

// alterTableTarget is the table a single ALTER TABLE ... SET/RESET (...)
// names; anything else (or a second statement) has none.
func alterTableTarget(sql string) (string, bool) {
	sql = strings.TrimSuffix(strings.TrimSpace(sql), ";")
	rest, ok := strings.CutPrefix(sql, "ALTER TABLE ")
	if !ok || strings.Contains(rest, ";") {
		return "", false
	}
	for _, verb := range []string{" SET (", " RESET ("} {
		if target, _, found := strings.Cut(rest, verb); found && target != "" {
			return strings.TrimSpace(target), true
		}
	}
	return "", false
}

func diagnoseFreezeBlockersSQL() string {
	return `SELECT datname,
       age(datfrozenxid) AS database_xid_age
FROM pg_database
ORDER BY database_xid_age DESC;

SELECT pid,
       usename,
       application_name,
       backend_xmin,
       age(backend_xmin) AS xmin_age,
       state,
       now() - xact_start AS transaction_age,
       left(query, 1000) AS query
FROM pg_stat_activity
WHERE backend_xmin IS NOT NULL
ORDER BY age(backend_xmin) DESC
LIMIT 20;`
}

func diagnoseVacuumPressureSQL(table string) string {
	tableFilter := ""
	if strings.TrimSpace(table) != "" {
		tableFilter = "WHERE relid = " +
			sanitize.QuoteLiteral(table) + "::regclass"
	}
	return `SELECT schemaname,
       relname,
       n_dead_tup,
       last_vacuum,
       last_autovacuum,
       vacuum_count,
       autovacuum_count
FROM pg_stat_user_tables
` + tableFilter + `;

SELECT pid,
       backend_xmin,
       age(backend_xmin) AS xmin_age,
       state,
       now() - xact_start AS transaction_age,
       left(query, 1000) AS query
FROM pg_stat_activity
WHERE backend_xmin IS NOT NULL
ORDER BY age(backend_xmin) DESC
LIMIT 20;`
}
