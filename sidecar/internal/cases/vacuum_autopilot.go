func vacuumAutopilotCandidate(f SourceFinding, classify SQLClassifier) (ActionCandidate, bool) {
	switch f.Category {
	case "table_bloat", "schema_lint:lint_bloated_table":
		return tableBloatCandidate(f, classify), true
	case "xid_wraparound", "wraparound_freeze", "schema_lint:lint_txid_age",
		"schema_lint:lint_mxid_age":
		return freezeDiagnosticCandidate(f), true
	case "vacuum_tuning", "autovacuum_tuning":
		return autovacuumTuningCandidate(f, classify), true
	case "bloat_remediation":
		return bloatRemediationCandidate(f), true
	default:
		return ActionCandidate{}, false
	}
}

func bloatRemediationCandidate(f SourceFinding) ActionCandidate {
	expires := evidenceTime(f).Add(7 * 24 * time.Hour)
	candidate := ActionCandidate{
		ActionType:       "plan_bloat_remediation",
		RiskTier:         "high",
		Confidence:       0.70,
		ExpiresAt:        &expires,
		OutputModes:      []string{"generate_pr_or_script"},
		RollbackClass:    "forward_fix_only",
		VerificationPlan: verificationPlanForAction("plan_bloat_remediation"),
		BlockedReason:    "bloat remediation requires reviewed online rebuild plan",
	}
	candidate.ScriptOutput = bloatRemediationScriptOutput(f, candidate)
	return candidate
}

// statementTyped gives a candidate that runs the finding's own statement
// the executor's classification of that statement (cases-04): an ALTER
// SYSTEM autovacuum setting is alter_system_guc, and a VACUUM FULL or a
// non-concurrent REINDEX is a script-only ddl_preflight, never the
// category's default type. A candidate without a statement, or one whose
// type the statement confirms, keeps its plan with the contract's tier.
func statementTyped(c ActionCandidate, classify SQLClassifier) ActionCandidate {
	if strings.TrimSpace(c.ProposedSQL) == "" {
		return c
	}
	actionType, riskTier := classifySQL(c.ProposedSQL, classify)
	if actionType == "" {
		actionType, riskTier = ddlPreflightType, ddlPreflightRisk
	}
	if actionType == c.ActionType {
		c.RiskTier = riskTier
		return c
	}
	c.ActionType, c.RiskTier = actionType, riskTier
	c.OutputModes = candidateOutputModes(actionType)
	c.RollbackClass, c.RecoveryDetail = rollbackClassForAction(actionType), ""
	c.VerificationPlan = verificationPlanForAction(actionType)
	return c
}

func bloatRemediationScriptOutput(
	f SourceFinding,
	candidate ActionCandidate,
) *ScriptOutput {
	table := f.ObjectIdentifier
	return &ScriptOutput{
		Filename: "bloat_remediation_" + sanitizeScriptPart(table) + ".sql",
		MigrationSQL: "-- Online bloat remediation plan generated by pg_sage\n" +
			"-- Prefer pg_repack or a reviewed online rebuild for " + table + ".\n" +
			"-- Avoid VACUUM FULL unless a maintenance outage is approved.\n",
		VerificationSQL: []string{
			"SELECT pg_total_relation_size(" +
				sanitize.QuoteLiteral(table) + "::regclass);",
			"-- Rerun bloat analyzer and confirm bloat ratio decreases.",
		},
		PRTitle: "Review bloat remediation plan: " + table,
		PRBody: "Generated from pg_sage case " + f.ID +
			". Risk tier: " + candidate.RiskTier + ".",
		RiskLabels: []string{"high", "forward_fix_only", "bloat_remediation"},
		Format:     "sql",
	}
}

func tableBloatCandidate(f SourceFinding, classify SQLClassifier) ActionCandidate {
	sql := strings.TrimSpace(f.RecommendedSQL)
	if sql == "" {
		sql = "VACUUM " + sanitize.QuoteQualifiedString(f.ObjectIdentifier) + ";"
	}
	expires := evidenceTime(f).Add(24 * time.Hour)
	candidate := ActionCandidate{
		ActionType:       "vacuum_table",
		RiskTier:         "safe",
		Confidence:       0.74,
		ProposedSQL:      sql,
		ExpiresAt:        &expires,
		OutputModes:      []string{"execute", "queue_for_approval", "generate_pr_or_script"},
		RollbackClass:    "no_rollback_needed",
		VerificationPlan: verificationPlanForAction("vacuum_table"),
	}
	candidate = statementTyped(candidate, classify)
	if detailBool(f.Detail, "io_saturated", false) {
		candidate.BlockedReason = "IO is saturated; wait for maintenance window or lower load"
		candidate.OutputModes = []string{"generate_pr_or_script"}
	}
	return candidate
}

func freezeDiagnosticCandidate(f SourceFinding) ActionCandidate {
	expires := evidenceTime(f).Add(30 * time.Minute)
	return ActionCandidate{
		ActionType:       "diagnose_freeze_blockers",
		RiskTier:         "safe",
		Confidence:       0.78,
		ProposedSQL:      diagnosticSQL("diagnose_freeze_blockers"),
		ExpiresAt:        &expires,
		OutputModes:      []string{"execute", "script"},
		RollbackClass:    "not_applicable",
		VerificationPlan: verificationPlanForAction("diagnose_freeze_blockers"),
	}
}

func autovacuumTuningCandidate(f SourceFinding, classify SQLClassifier) ActionCandidate {
	sql := strings.TrimSpace(f.RecommendedSQL)
	expires := evidenceTime(f).Add(72 * time.Hour)
	candidate := ActionCandidate{
		ActionType:       "set_table_autovacuum",
		RiskTier:         "moderate",
		Confidence:       0.72,
		ProposedSQL:      sql,
		ExpiresAt:        &expires,
		OutputModes:      []string{"queue_for_approval", "generate_pr_or_script"},
		RollbackClass:    "unknown",
		RecoveryDetail:   "The previous table storage parameters have not been captured. Capture which settings were explicit and their values before preparing recovery; RESET may not restore the previous state.",
		VerificationPlan: verificationPlanForAction("set_table_autovacuum"),
	}
	candidate = statementTyped(candidate, classify)
	candidate.ScriptOutput = scriptOutputFromFinding(f, candidate)
	if rollback, ok := capturedReloptionRollback(sql, f.RollbackSQL); ok {
		candidate.RollbackClass = "reversible"
		candidate.RecoveryDetail = "The finding captured the table's previous storage " +
			"parameters; the rollback restores them."
		candidate.ScriptOutput.RollbackSQL = rollback
	}
	return candidate
}
