package cases

import (
	"strings"
	"time"

	"github.com/pg-sage/sidecar/internal/sanitize"
)

// runawayPolicyOwnsSignalReason blocks a case cancel of a runaway query:
// the executor's runaway policy already signals that backend under its
// own identity checks, and a second signal from a case would race it.
const runawayPolicyOwnsSignalReason = "the executor's runaway policy owns " +
	"cancel and terminate for this backend"

// findingPlaybookCandidates maps the analyzer and executor finding
// categories whose incident-style playbooks lived behind signal ids RCA
// never emits (playbooks-02). ok is false for every other category.
func findingPlaybookCandidates(f SourceFinding) ([]ActionCandidate, bool) {
	switch f.Category {
	case "sequence_exhaustion":
		return sequenceCapacityCandidates(f), true
	case "inactive_slot", "replication_lag":
		// Read-only: an inactive slot's pg_drop_replication_slot SQL is
		// never proposed; dropping a slot loses its consumer's position.
		return []ActionCandidate{findingDiagnosticCandidate(f,
			"diagnose_wal_replication", diagnoseWALReplicationSQL(),
			[]string{"verify WAL retention, slot status, and replay lag"})}, true
	case "runaway_query":
		expires := evidenceTime(f).Add(15 * time.Minute)
		return []ActionCandidate{
			findingDiagnosticCandidate(f, "diagnose_runaway_query",
				diagnoseRunawayQuerySQL(),
				[]string{"confirm query age, wait state, and temp spill evidence"}),
			blockedSignalCandidate("cancel_backend", runawayPolicyOwnsSignalReason,
				expires, findingDiagnosticConfidence),
		}, true
	default:
		return nil, false
	}
}

// findingDiagnosticConfidence is the confidence of a read-only diagnostic
// derived from a deterministic analyzer or executor measurement.
const findingDiagnosticConfidence = 0.80

func findingDiagnosticCandidate(f SourceFinding, actionType, sql string,
	verification []string) ActionCandidate {
	expires := evidenceTime(f).Add(15 * time.Minute)
	return ActionCandidate{
		ActionType:       actionType,
		RiskTier:         "safe",
		Confidence:       findingDiagnosticConfidence,
		ProposedSQL:      sql,
		ExpiresAt:        &expires,
		OutputModes:      []string{"execute", "script"},
		RollbackClass:    "not_applicable",
		VerificationPlan: verification,
	}
}

// sequenceCapacityCandidates is the review-only migration script for a
// sequence near its limit. Without a sequence name there is nothing to
// migrate, so no candidate is offered.
func sequenceCapacityCandidates(f SourceFinding) []ActionCandidate {
	object := strings.TrimSpace(f.ObjectIdentifier)
	if object == "" {
		return nil
	}
	quoted := sanitize.QuoteQualifiedString(object)
	expires := evidenceTime(f).Add(24 * time.Hour)
	return []ActionCandidate{{
		ActionType:       "prepare_sequence_capacity_migration",
		RiskTier:         "high",
		Confidence:       findingDiagnosticConfidence,
		ExpiresAt:        &expires,
		OutputModes:      []string{"generate_pr_or_script"},
		RollbackClass:    "forward_fix_only",
		VerificationPlan: []string{"run verification SQL before and after migration"},
		BlockedReason:    "direct sequence capacity changes require migration review",
		ScriptOutput: &ScriptOutput{
			Filename:     "sequence_capacity_" + sanitizeScriptPart(object) + ".sql",
			MigrationSQL: sequenceCapacityMigrationSQL(quoted),
			VerificationSQL: []string{
				"SELECT last_value, max_value FROM " + quoted + ";",
				"-- Confirm dependent column type can hold future generated values.",
			},
			PRTitle: "Review sequence capacity migration: " + object,
			PRBody: "Generated from pg_sage finding " + f.ID +
				". Sequence exhaustion is forward-fix only and must be reviewed.",
			RiskLabels: []string{"high", "forward_fix_only", "sequence_exhaustion"},
			Format:     "sql",
		},
	}}
}

// sequenceCapacityMigrationSQL takes an already quoted sequence name.
func sequenceCapacityMigrationSQL(quotedSequence string) string {
	return `-- Forward-fix sequence capacity migration generated by pg_sage
-- Inspect the owning table and column before editing this migration.
SELECT pg_get_serial_sequence('', '') AS owning_sequence;
SELECT last_value, max_value FROM ` + quotedSequence + `;
-- Preferred migration is usually widening the owning column to bigint
-- or replacing the sequence with an identity column under a reviewed rollout.`
}
