// Integration (playbooks-03): the sequence forward-fix script runs on real
// PostgreSQL. Its reads run in READ ONLY transactions; its one DDL step,
// the guarded ALTER SEQUENCE, runs in a transaction that is rolled back.
// No concurrent access tests: each fixture is private to this test.

var sequenceFixtureSQL = []string{
	`DROP SCHEMA IF EXISTS pb03 CASCADE`,
	`DROP SCHEMA IF EXISTS "Odd" CASCADE`,
	`DROP ROLE IF EXISTS pb03_reader`,
	`CREATE ROLE pb03_reader NOLOGIN`,
	`CREATE SCHEMA pb03`,
	`GRANT USAGE ON SCHEMA pb03 TO pb03_reader`,
	`CREATE TABLE pb03.big (id bigint GENERATED ALWAYS AS IDENTITY)`,
	`CREATE SEQUENCE pb03.small_seq AS smallint`,
	`CREATE TABLE pb03.sm (id integer DEFAULT nextval('pb03.small_seq'))`,
	`CREATE SEQUENCE pb03.down_full AS integer INCREMENT BY -1`,
	`CREATE TABLE pb03.dcol (id integer DEFAULT nextval('pb03.down_full'))`,
	`CREATE TABLE pb03.ident (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)`,
	`INSERT INTO pb03.ident DEFAULT VALUES`,
	`CREATE TABLE pb03.narrow (id integer NOT NULL)`,
	`CREATE SEQUENCE pb03.narrow_seq AS bigint OWNED BY pb03.narrow.id`,
	`CREATE TABLE pb03.wide (id bigint NOT NULL)`,
	`CREATE SEQUENCE pb03.wide_seq AS integer OWNED BY pb03.wide.id`,
	`CREATE SEQUENCE pb03.loose_seq AS bigint`,
	`CREATE TABLE pb03.loose (id integer DEFAULT nextval('pb03.loose_seq'))`,
	`CREATE SEQUENCE pb03.down AS integer INCREMENT BY -1 MINVALUE -100 MAXVALUE -1 START -1`,
	`SELECT nextval('pb03.down') FROM generate_series(1, 10)`,
	`CREATE SCHEMA "Odd"`,
	`CREATE SEQUENCE "Odd"."Seq""x" AS integer`,
	`SELECT nextval('"Odd"."Seq""x"')`,
}

func sequenceTestConn(t *testing.T) *pgx.Conn {
	t.Helper()
	conn := guardedConnect(t, guardedDSN(t), "", "")
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	for _, stmt := range sequenceFixtureSQL {
		if _, err := conn.Exec(ctx, stmt); err != nil {
			t.Fatalf("fixture %s: %v", stmt, err)
		}
	}
	t.Cleanup(func() {
		for _, s := range []string{"pb03", `"Odd"`} {
			_, _ = conn.Exec(context.Background(), "DROP SCHEMA IF EXISTS "+s+" CASCADE")
		}
		_, _ = conn.Exec(context.Background(), "DROP ROLE IF EXISTS pb03_reader")
	})
	return conn
}

// splitSQLScript cuts a script at top-level semicolons, keeping quoted
// strings, quoted identifiers, dollar-quoted bodies and comments intact.
func splitSQLScript(script string) []string {
	var out []string
	start, tag := 0, ""
	for i := 0; i < len(script); i++ {
		switch {
		case tag != "":
			if strings.HasPrefix(script[i:], tag) {
				i += len(tag) - 1
				tag = ""
			}
		case strings.HasPrefix(script[i:], "--"):
			i += strings.IndexByte(script[i:]+"\n", '\n')
		case script[i] == '\'' || script[i] == '"':
			i += 1 + strings.IndexByte(script[i+1:], script[i])
		case script[i] == '$':
			if end := strings.IndexByte(script[i+1:], '$'); end >= 0 {
				tag = script[i : i+end+2]
				i += end + 1
			}
		case script[i] == ';':
			out = appendStatement(out, script[start:i+1])
			start = i + 1
		}
	}
	return appendStatement(out, script[start:])
}

// appendStatement appends stmt without its leading comment lines, or
// nothing when it holds only comments.
func appendStatement(out []string, stmt string) []string {
	lines := strings.Split(stmt, "\n")
	for i, line := range lines {
		line = strings.TrimSpace(line)
		if line != "" && !strings.HasPrefix(line, "--") {
			return append(out, strings.TrimSpace(strings.Join(lines[i:], "\n")))
		}
	}
	return out
}

func inReadOnlyTx(t *testing.T, conn *pgx.Conn, sql string, scan ...any) {
	t.Helper()
	ctx := context.Background()
	tx, err := conn.BeginTx(ctx, pgx.TxOptions{AccessMode: pgx.ReadOnly})
	if err != nil {
		t.Fatalf("begin read only: %v", err)
	}
	defer func() { _ = tx.Rollback(ctx) }()
	if len(scan) == 0 {
		_, err = tx.Exec(ctx, sql)
	} else {
		err = tx.QueryRow(ctx, sql).Scan(scan...)
	}
	if err != nil {
		t.Fatalf("read-only run failed: %v\n%s", err, sql)
	}
}

type sequenceRunway struct {
	dataType, binding string
	column, colType   *string
	limit, remaining  string
}

func readRunway(t *testing.T, conn *pgx.Conn, script *ScriptOutput) sequenceRunway {
	t.Helper()
	var r sequenceRunway
	q := "SELECT data_type, binding_limit, owning_column, column_type, " +
		"effective_limit::text, remaining_values::text FROM (" +
		strings.TrimSuffix(script.VerificationSQL[0], ";") + ") v"
	inReadOnlyTx(t, conn, q, &r.dataType, &r.binding, &r.column, &r.colType,
		&r.limit, &r.remaining)
	return r
}

// Every statement before the first DDL and every verification statement
// runs in a READ ONLY transaction; the DDL step is the guarded ALTER.
func TestSequenceScriptReadsRunReadOnly(t *testing.T) {
	conn := sequenceTestConn(t)
	script := sequenceScript(t, "pb03.ident_id_seq")
	stmts := splitSQLScript(script.MigrationSQL)
	reads := 0
	for _, stmt := range stmts {
		if strings.Contains(stmt, "ALTER SEQUENCE") {
			break
		}
		inReadOnlyTx(t, conn, stmt)
		reads++
	}
	if reads == 0 || reads == len(stmts) {
		t.Fatalf("want reads then the DDL step, got %d reads of %d:\n%s",
			reads, len(stmts), script.MigrationSQL)
	}
	if !strings.HasPrefix(stmts[reads], "DO $") || len(stmts) != reads+1 {
		t.Fatalf("DDL step is not one guarded DO block:\n%v", stmts[reads:])
	}
	for _, v := range script.VerificationSQL {
		inReadOnlyTx(t, conn, v)
	}
}

// guardedAlter runs the script's DO step in a transaction it rolls back
// and returns the step's error and the data type and binding limit the
// runway reported inside, after the step.
func guardedAlter(t *testing.T, conn *pgx.Conn, ident string) (string, string, error) {
	t.Helper()
	script := sequenceScript(t, ident)
	stmts := splitSQLScript(script.MigrationSQL)
	ctx := context.Background()
	tx, err := conn.Begin(ctx)
	if err != nil {
		t.Fatalf("begin: %v", err)
	}
	defer func() { _ = tx.Rollback(ctx) }()
	if _, err := tx.Exec(ctx, stmts[len(stmts)-1]); err != nil {
		return "", "", err
	}
	var typ, binding string
	q := "SELECT data_type, binding_limit FROM (" +
		strings.TrimSuffix(script.VerificationSQL[0], ";") + ") v"
	if err := tx.QueryRow(ctx, q).Scan(&typ, &binding); err != nil {
		t.Fatalf("runway after ALTER: %v", err)
	}
	return typ, binding, nil
}

func wantGuardRefusal(t *testing.T, conn *pgx.Conn, ident, column string) {
	t.Helper()
	_, _, err := guardedAlter(t, conn, ident)
	var pgErr *pgconn.PgError
	if !errors.As(err, &pgErr) || pgErr.Code != "P0001" ||
		!strings.Contains(pgErr.Message, column) || !strings.Contains(pgErr.Message, "widen") {
		t.Fatalf("%s: guard did not refuse for %s: %v", ident, column, err)
	}
}

// Happy path, column limit: an integer identity column, a bigint sequence
// owning an integer column, and an integer column fed only by a DEFAULT
// nextval all report the column as the limit, and the guard refuses the
// ALTER SEQUENCE until the column is widened.
func TestSequenceScriptColumnLimitRefusesAlter(t *testing.T) {
	conn := sequenceTestConn(t)
	for _, tc := range []struct{ ident, dataType, limit string }{
		{"pb03.ident_id_seq", "integer", "2147483647"},
		{"pb03.narrow_seq", "bigint", "2147483647"},
		{"pb03.loose_seq", "bigint", "2147483647"},
	} {
		r := readRunway(t, conn, sequenceScript(t, tc.ident))
		if r.dataType != tc.dataType || r.binding != "column" || r.limit != tc.limit ||
			r.column == nil || *r.column != "id" || r.colType == nil || *r.colType != "integer" {
			t.Fatalf("%s runway = %+v", tc.ident, r)
		}
		wantGuardRefusal(t, conn, tc.ident, "integer")
	}
}

// Happy path, sequence limit: an integer sequence feeding a bigint column
// is widened by the ALTER SEQUENCE, which the rollback undoes.
func TestSequenceScriptWidensSequenceTypeInRolledBackTx(t *testing.T) {
	conn := sequenceTestConn(t)
	r := readRunway(t, conn, sequenceScript(t, "pb03.wide_seq"))
	if r.binding != "sequence" || r.dataType != "integer" || r.limit != "2147483647" {
		t.Fatalf("wide_seq runway = %+v", r)
	}
	typ, _, err := guardedAlter(t, conn, "pb03.wide_seq")
	if err != nil || typ != "bigint" {
		t.Fatalf("guarded ALTER = %q, %v; want bigint", typ, err)
	}
	after := readRunway(t, conn, sequenceScript(t, "pb03.wide_seq"))
	if after.dataType != "integer" {
		t.Fatalf("rollback left data_type %q", after.dataType)
	}
}

// Invalid input: a mixed-case name with an embedded quote resolves, and
// the guard lets its ALTER through (no column takes its values).
func TestSequenceScriptResolvesMixedCaseName(t *testing.T) {
	conn := sequenceTestConn(t)
	r := readRunway(t, conn, sequenceScript(t, `Odd.Seq"x`))
	if r.binding != "sequence" || r.column != nil || r.remaining != "2147483646" {
		t.Fatalf(`"Odd"."Seq""x" runway = %+v`, r)
	}
	if typ, _, err := guardedAlter(t, conn, `Odd.Seq"x`); err != nil || typ != "bigint" {
		t.Fatalf("guarded ALTER = %q, %v", typ, err)
	}
}

// Boundary: a descending sequence's runway runs toward its min_value.
func TestSequenceScriptDescendingRunway(t *testing.T) {
	conn := sequenceTestConn(t)
	r := readRunway(t, conn, sequenceScript(t, "pb03.down"))
	if r.binding != "sequence" || r.limit != "-100" || r.remaining != "90" {
		t.Fatalf("descending runway = %+v, want limit -100 and 90 values left", r)
	}
}

// Error propagation: a sequence that does not exist fails with the
// catalog's own error, not a silent empty runway.
func TestSequenceScriptMissingSequenceErrors(t *testing.T) {
	conn := sequenceTestConn(t)
	script := sequenceScript(t, "pb03.no_such_seq")
	_, err := conn.Exec(context.Background(), script.VerificationSQL[0])
	var pgErr *pgconn.PgError
	if !errors.As(err, &pgErr) || pgErr.Code != "42P01" {
		t.Fatalf("missing sequence error = %v, want 42P01", err)
	}
}

// Boundary: a bigint sequence feeding a bigint column cannot be fixed by
// widening the column, so the sequence is the limit and the guard passes.
func TestSequenceScriptBigintColumnIsSequenceBound(t *testing.T) {
	conn := sequenceTestConn(t)
	r := readRunway(t, conn, sequenceScript(t, "pb03.big_id_seq"))
	if r.binding != "sequence" || r.colType == nil || *r.colType != "bigint" ||
		r.limit != "9223372036854775807" {
		t.Fatalf("bigint identity runway = %+v, want the sequence as the limit", r)
	}
	if typ, _, err := guardedAlter(t, conn, "pb03.big_id_seq"); err != nil || typ != "bigint" {
		t.Fatalf("guarded ALTER on a bigint column = %q, %v; want it to pass", typ, err)
	}
}

// State transition: a smallint sequence feeding an integer column is bound
// by the sequence, so step 2 runs; afterwards the column is the limit.
func TestSequenceScriptSmallintSequenceWidensBeforeColumn(t *testing.T) {
	conn := sequenceTestConn(t)
	r := readRunway(t, conn, sequenceScript(t, "pb03.small_seq"))
	if r.binding != "sequence" || r.limit != "32767" || r.colType == nil ||
		*r.colType != "integer" {
		t.Fatalf("smallint sequence runway = %+v", r)
	}
	typ, binding, err := guardedAlter(t, conn, "pb03.small_seq")
	if err != nil || typ != "bigint" || binding != "column" {
		t.Fatalf("after guarded ALTER: type %q limit %q err %v; want bigint, column",
			typ, binding, err)
	}
}

// Boundary: a descending integer sequence at the type's default MINVALUE
// on an integer column is bound by the column, and the guard refuses.
func TestSequenceScriptDescendingColumnLimitRefuses(t *testing.T) {
	conn := sequenceTestConn(t)
	r := readRunway(t, conn, sequenceScript(t, "pb03.down_full"))
	if r.binding != "column" || r.limit != "-2147483648" {
		t.Fatalf("descending column runway = %+v, want column limit -2147483648", r)
	}
	wantGuardRefusal(t, conn, "pb03.down_full", "integer")
}

// Error path: a role that cannot read the sequence's last_value gets no
// remaining_values, not a full runway computed from start_value.
func TestSequenceRunwayWithoutPrivilegeHasNoRemaining(t *testing.T) {
	conn := sequenceTestConn(t)
	ctx := context.Background()
	q := "SELECT binding_limit, remaining_values::text FROM (" +
		strings.TrimSuffix(sequenceScript(t, "pb03.ident_id_seq").VerificationSQL[0], ";") +
		") v"
	tx, err := conn.BeginTx(ctx, pgx.TxOptions{AccessMode: pgx.ReadOnly})
	if err != nil {
		t.Fatalf("begin: %v", err)
	}
	defer func() { _ = tx.Rollback(ctx) }()
	if _, err := tx.Exec(ctx, "SET LOCAL ROLE pb03_reader"); err != nil {
		t.Fatalf("set role: %v", err)
	}
	var binding string
	var remaining *string
	if err := tx.QueryRow(ctx, q).Scan(&binding, &remaining); err != nil {
		t.Fatalf("runway as an unprivileged role: %v", err)
	}
	if binding != "column" || remaining != nil {
		t.Fatalf("unprivileged runway: limit %q remaining %v; want column and NULL",
			binding, remaining)
	}
}
