// tuning-11 review: query_parameterization findings carry workload text from
// pg_stat_statements, which keeps a statement's own comments. PostgreSQL ends
// a "--" comment at \r too, so every \r- or \n-separated line of the script
// must stay commented out.
func TestParameterizedQueryScript_EveryLineCommented(t *testing.T) {
	for _, q := range []string{
		"SELECT 1 FROM t /*\rDROP TABLE t; */ WHERE id IN (...)",
		"SELECT 1 FROM t /*\r\nDROP TABLE t; */ WHERE id IN (...)",
		"SELECT 1\nFROM t\n\rWHERE id IN (...)",
		"",
	} {
		out := parameterizedQueryScriptOutput(SourceFinding{ID: "7",
			Category: "query_parameterization", ObjectIdentifier: "shape:ab",
			Detail: map[string]any{"normalized_query": q}})
		for _, line := range regexp.MustCompile(`\r\n|\r|\n`).Split(out.MigrationSQL, -1) {
			if line != "" && !strings.HasPrefix(line, "--") {
				t.Errorf("query %q: uncommented script line %q in\n%s", q, line, out.MigrationSQL)
			}
		}
		if strings.Contains(out.MigrationSQL, "\r") {
			t.Errorf("query %q: script keeps a carriage return", q)
		}
	}
}

// The shape text itself survives, one commented line per query line.
func TestParameterizedQueryScript_KeepsTheShape(t *testing.T) {
	out := parameterizedQueryScriptOutput(SourceFinding{ID: "7",
		Detail: map[string]any{"normalized_query": "SELECT a\nFROM t WHERE id IN (...)"}})
	want := "-- Application query parameterization plan generated by pg_sage\n" +
		"-- Normalized query shape:\n-- SELECT a\n-- FROM t WHERE id IN (...)\n"
	if out.MigrationSQL != want {
		t.Fatalf("script = %q, want %q", out.MigrationSQL, want)
	}
}

func TestSQLLineComment(t *testing.T) {
	cases := map[string]string{
		"":         "-- ",
		"a":        "-- a",
		"a\nb":     "-- a\n-- b",
		"a\r\nb":   "-- a\n-- b",
		"a\rb":     "-- a\n-- b",
		"a\r\rb\n": "-- a\n-- \n-- b\n-- ",
	}
	for in, want := range cases {
		if got := sqlLineComment(in); got != want {
			t.Errorf("sqlLineComment(%q) = %q, want %q", in, got, want)
		}
	}
}
