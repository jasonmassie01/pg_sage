func cronLimitedRole(t *testing.T, pool *pgxpool.Pool, q string) string {
	t.Helper()
	role := "sage_ext_reader"
	_, _ = pool.Exec(context.Background(), "DROP OWNED BY "+role)
	_, _ = pool.Exec(context.Background(), "DROP ROLE IF EXISTS "+role)
	extExec(t, pool, "CREATE ROLE "+role+" NOLOGIN")
	t.Cleanup(func() {
		_, _ = pool.Exec(context.Background(), "DROP OWNED BY "+role)
		_, _ = pool.Exec(context.Background(), "DROP ROLE IF EXISTS "+role)
	})
	extExec(t, pool, "GRANT USAGE ON SCHEMA "+q+" TO "+role)
	extExec(t, pool, "GRANT SELECT ON "+q+".job TO "+role)
	return role
}

// readAs runs the extension reading on one connection as role.
func readAs(t *testing.T, a *Analyzer, pool *pgxpool.Pool, role string) {
	t.Helper()
	ctx := context.Background()
	conn, err := pool.Acquire(ctx)
	if err != nil {
		t.Fatalf("acquire: %v", err)
	}
	defer func() {
		_, _ = conn.Exec(ctx, "RESET ROLE")
		conn.Release()
	}()
	if _, err := conn.Exec(ctx, "SET ROLE "+role); err != nil {
		t.Fatalf("set role: %v", err)
	}
	a.eval = newCycleEval()
	a.readExtensions(ctx, catalogread.New(conn, catalogread.Default()))
}

func TestExtCron_PermissionDeniedIsNotEvaluated(t *testing.T) {
	a, pool, logs := extAnalyzer(t, map[string]extInstall{extPgCron: {Schema: "cron"}})
	q := cronStub(t, pool, "cron")
	extExec(t, pool, `INSERT INTO `+q+`.job (jobid) VALUES (8)`)
	cronRun(t, pool, q, 8, "failed", "e", extTestNow.Add(-time.Minute))
	runExtCycle(t, a) // opens the finding as a privileged reader
	role := cronLimitedRole(t, pool, q)

	readAs(t, a, pool, role)
	if !a.eval.hasFailed(categoryCronJobFailed) {
		t.Fatal("pg_cron_job_failed evaluated without SELECT on job_run_details")
	}
	if a.eval.hasFailed(categoryCronHistory) {
		t.Fatal("pg_cron_history_unbounded failed: it reads only pg_class")
	}
	if got := rulePgCronJobFailed(nil, nil, nil, a.extras); len(got) != 0 {
		t.Fatalf("an unread history emitted %+v", got)
	}
	err := a.finalizeCycle(context.Background(), nil, a.eval.resolvable(nil))
	if err != nil {
		t.Fatalf("finalize: %v", err)
	}
	if n := countFindingRows(t, pool, categoryCronJobFailed, "pg_cron:job:8", "open"); n != 1 {
		t.Fatalf("open rows after a denied read = %d, want 1 (left open)", n)
	}
	readAs(t, a, pool, role)
	if n := logs.warns("job_run_details"); n != 1 {
		t.Fatalf("WARN lines naming job_run_details = %d over a streak of 2, want 1", n)
	}
	extExec(t, pool, "GRANT SELECT ON "+q+".job_run_details TO "+role)
	readAs(t, a, pool, role)
	if a.eval.hasFailed(categoryCronJobFailed) {
		t.Fatal("pg_cron_job_failed failed after the grant")
	}
	extExec(t, pool, "REVOKE SELECT ON "+q+".job_run_details FROM "+role)
	readAs(t, a, pool, role)
	if n := logs.warns("job_run_details"); n != 2 {
		t.Fatalf("WARN lines after a second streak = %d, want 2", n)
	}
}

