// market-16 on real PostgreSQL. The local images carry neither pg_cron nor
// pg_partman, so each test builds a stub schema with the same table and
// column shapes (cron.job, cron.job_run_details; partman.part_config and
// SQL stubs of show_partitions and show_partition_info) and injects the
// gate that would have found the extension.
// No concurrent access tests: the extension reading belongs to one cycle on
// the analyzer's cycle goroutine.

var extTestNow = time.Date(2026, 11, 13, 12, 0, 0, 0, time.UTC)

type extLog struct {
	mu    sync.Mutex
	lines []string
}

func (l *extLog) log(level, format string, args ...any) {
	l.mu.Lock()
	defer l.mu.Unlock()
	l.lines = append(l.lines, level+" "+fmt.Sprintf(format, args...))
}

func (l *extLog) warns(substr string) int {
	l.mu.Lock()
	defer l.mu.Unlock()
	n := 0
	for _, line := range l.lines {
		if strings.HasPrefix(line, "WARN ") && strings.Contains(line, substr) {
			n++
		}
	}
	return n
}

func extAnalyzer(t *testing.T, installs map[string]extInstall) (*Analyzer, *pgxpool.Pool, *extLog) {
	t.Helper()
	pool := phase2Pool(t)
	for _, c := range extCategories {
		cleanCategory(t, pool, c)
	}
	logs := &extLog{}
	a := New(pool, phase2Config(), nil, nil, nil, nil, nil, logs.log)
	a.extras.Now = func() time.Time { return extTestNow }
	a.extGate = func(context.Context, catalogread.Querier) (map[string]extInstall, error) {
		return installs, nil
	}
	return a, pool, logs
}

func extExec(t *testing.T, pool *pgxpool.Pool, sql string, args ...any) {
	t.Helper()
	if _, err := pool.Exec(context.Background(), sql, args...); err != nil {
		t.Fatalf("exec %q: %v", sql, err)
	}
}

// cronStub creates a pg_cron-shaped schema and returns its quoted name.
func cronStub(t *testing.T, pool *pgxpool.Pool, schema string) string {
	t.Helper()
	q := sqlident.Ident(schema)
	extExec(t, pool, "DROP SCHEMA IF EXISTS "+q+" CASCADE")
	extExec(t, pool, "CREATE SCHEMA "+q)
	t.Cleanup(func() {
		_, _ = pool.Exec(context.Background(), "DROP SCHEMA IF EXISTS "+q+" CASCADE")
	})
	extExec(t, pool, `CREATE TABLE `+q+`.job (jobid bigint PRIMARY KEY,
		schedule text NOT NULL DEFAULT '* * * * *', command text NOT NULL DEFAULT 'SELECT 1',
		nodename text NOT NULL DEFAULT 'localhost', nodeport int NOT NULL DEFAULT 5432,
		database text NOT NULL DEFAULT current_database(),
		username text NOT NULL DEFAULT current_user, active boolean NOT NULL DEFAULT true,
		jobname text)`)
	extExec(t, pool, `CREATE TABLE `+q+`.job_run_details (jobid bigint,
		runid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, job_pid int,
		database text, username text NOT NULL DEFAULT current_user, command text,
		status text, return_message text, start_time timestamptz, end_time timestamptz)`)
	return q
}

func cronRun(t *testing.T, pool *pgxpool.Pool, q string, job int64, status, msg string,
	end time.Time) {
	t.Helper()
	extExec(t, pool, `INSERT INTO `+q+`.job_run_details
		(jobid, status, return_message, start_time, end_time)
		VALUES ($1, $2, $3, $4, $4)`, job, status, msg, end)
}

// runExtCycle runs the extension part of one cycle and finalizes it: the
// extension rules exactly as runSnapshotRules runs them.
func runExtCycle(t *testing.T, a *Analyzer) []Finding {
	t.Helper()
	return runExtCycleWith(t, a, a.loadExtensionState)
}

// runExtCycleWith is runExtCycle with load as the cycle's extension read.
func runExtCycleWith(t *testing.T, a *Analyzer, load func(context.Context)) []Finding {
	t.Helper()
	ctx := context.Background()
	a.eval = newCycleEval()
	load(ctx)
	var got []Finding
	for _, rule := range AllRules {
		if !isExtCategory(rule.Name) || a.ruleDisabled(rule) {
			continue
		}
		a.eval.evaluated(rule.Categories...)
		got = append(got, rule.Fn(&collector.Snapshot{}, nil, a.cfg, a.extras)...)
		for category, idents := range a.extras.takeUndecided() {
			a.eval.keep(category, idents...)
		}
	}
	got = a.applyDisabledRules(got)
	res := map[string]bool{}
	for c, ok := range a.eval.resolvable(got) {
		if ok && isExtCategory(c) {
			res[c] = true
		}
	}
	if err := a.finalizeCycle(ctx, got, res); err != nil {
		t.Fatalf("finalizeCycle: %v", err)
	}
	return got
}

func byCategory(fs []Finding, cat string) []Finding {
	var out []Finding
	for _, f := range fs {
		if f.Category == cat {
			out = append(out, f)
		}
	}
	return out
}

func storedDetail(t *testing.T, pool *pgxpool.Pool, cat, ident, key string) string {
	t.Helper()
	var v string
	err := pool.QueryRow(context.Background(), `SELECT COALESCE(detail->>$3, '')
		FROM sage.findings WHERE category = $1 AND object_identifier = $2
		ORDER BY id DESC LIMIT 1`, cat, ident, key).Scan(&v)
	if err != nil {
		t.Fatalf("read %s detail %s: %v", ident, key, err)
	}
	return v
}

func TestExtCron_ThreeFailuresGiveOneFinding(t *testing.T) {
	a, pool, _ := extAnalyzer(t, map[string]extInstall{extPgCron: {Schema: "cron"}})
	q := cronStub(t, pool, "cron")
	extExec(t, pool, `INSERT INTO `+q+`.job (jobid, jobname) VALUES (7, 'nightly')`)
	for i := 1; i <= 3; i++ {
		cronRun(t, pool, q, 7, "failed", "ERROR: boom", extTestNow.Add(-time.Duration(i)*time.Hour))
	}
	cronRun(t, pool, q, 7, "succeeded", "", extTestNow.Add(-5*time.Hour))
	got := byCategory(runExtCycle(t, a), categoryCronJobFailed)
	if len(got) != 1 {
		t.Fatalf("pg_cron_job_failed = %+v, want one", got)
	}
	d := got[0].Detail
	if d["failures"] != int64(3) || d["jobid"] != int64(7) || d["jobname"] != "nightly" ||
		d["last_failed_at"] != extTestNow.Add(-time.Hour).Format(time.RFC3339) {
		t.Fatalf("detail = %+v", d)
	}
	if n := countFindingRows(t, pool, categoryCronJobFailed, "pg_cron:job:7", "open"); n != 1 {
		t.Fatalf("open rows = %d, want 1", n)
	}
	if !a.eval.ok[categoryCronJobFailed] || a.eval.hasFailed(categoryCronJobFailed) {
		t.Fatalf("pg_cron_job_failed not evaluated: %+v", a.eval)
	}
}

