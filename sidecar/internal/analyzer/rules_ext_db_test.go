// countingReader counts the statements a reading runs.
func countingReader(pool *pgxpool.Pool, n *int) catalogread.Reader {
	r := catalogread.New(pool, catalogread.Default())
	r.Done = func(context.Context, catalogread.ReadStat) { *n++ }
	return r
}

func TestExtGate_NoExtensionRunsOnlyTheGate(t *testing.T) {
	pool := phase2Pool(t)
	a := New(pool, phase2Config(), nil, nil, nil, nil, nil, noopLog)
	a.eval = newCycleEval()
	var n int
	a.readExtensions(context.Background(), countingReader(pool, &n))
	if n != 1 {
		t.Fatalf("statements without the extensions = %d, want 1 (the gate)", n)
	}
	for _, c := range extCategories {
		if !a.eval.hasFailed(c) {
			t.Errorf("%s evaluated without its extension", c)
		}
	}
	if got := rulePgCronJobFailed(nil, nil, nil, a.extras); len(got) != 0 {
		t.Fatalf("no extension emitted %+v", got)
	}
}

