func TestExtGate_ErrorFailsAllAndWarnsOncePerStreak(t *testing.T) {
	a, _, logs := extAnalyzer(t, nil)
	calls := 0
	a.extGate = func(context.Context, catalogread.Querier) (map[string]extInstall, error) {
		calls++
		if calls == 3 {
			return nil, nil
		}
		return nil, errors.New("permission denied for table pg_extension")
	}
	for i := 0; i < 4; i++ {
		a.eval = newCycleEval()
		a.loadExtensionState(context.Background())
		for _, c := range extCategories {
			if !a.eval.hasFailed(c) {
				t.Fatalf("cycle %d: %s evaluated after a failed gate", i, c)
			}
		}
	}
	if n := logs.warns("pg_extension"); n != 2 {
		t.Fatalf("gate WARN lines = %d over two streaks, want 2", n)
	}
}
