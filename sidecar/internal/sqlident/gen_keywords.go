//go:build ignore

// gen_keywords writes keywords_gen.go from pg_get_keywords() on every
// server in SQLIDENT_KEYWORD_URLS (space-separated connection URLs). Pass
// one server per supported major version: the table is their union, so a
// key word any of them needs quoted is quoted.
//
//	SQLIDENT_KEYWORD_URLS="postgres://...pg14 postgres://...pg18" go generate
package main

import (
	"bytes"
	"context"
	"fmt"
	"go/format"
	"log"
	"os"
	"sort"
	"strings"
	"time"

	"github.com/jackc/pgx/v5"
)

func main() {
	urls := strings.Fields(os.Getenv("SQLIDENT_KEYWORD_URLS"))
	if len(urls) == 0 {
		log.Fatal("set SQLIDENT_KEYWORD_URLS to the servers to read key words from")
	}
	words := map[string]string{}
	var versions []string
	for _, u := range urls {
		v, err := readKeywords(u, words)
		if err != nil {
			log.Fatalf("read key words: %v", err)
		}
		versions = append(versions, v)
	}
	src, err := render(words, versions)
	if err != nil {
		log.Fatalf("format keywords_gen.go: %v", err)
	}
	if err := os.WriteFile("keywords_gen.go", src, 0o644); err != nil {
		log.Fatalf("write keywords_gen.go: %v", err)
	}
}

func readKeywords(url string, words map[string]string) (string, error) {
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	conn, err := pgx.Connect(ctx, url)
	if err != nil {
		return "", fmt.Errorf("connect: %w", err)
	}
	defer conn.Close(ctx)
	var version string
	if err := conn.QueryRow(ctx, `SELECT (pg_catalog.current_setting('server_version_num')::int
  / 10000)::text`).Scan(&version); err != nil {
		return "", fmt.Errorf("server_version_num: %w", err)
	}
	rows, err := conn.Query(ctx, `SELECT word, catcode::text
FROM pg_catalog.pg_get_keywords() WHERE catcode <> 'U'`)
	if err != nil {
		return "", fmt.Errorf("pg_get_keywords on %s: %w", version, err)
	}
	defer rows.Close()
	for rows.Next() {
		var w, c string
		if err := rows.Scan(&w, &c); err != nil {
			return "", fmt.Errorf("scan pg_get_keywords: %w", err)
		}
		words[w] = c
	}
	return version, rows.Err()
}

func render(words map[string]string, versions []string) ([]byte, error) {
	keys := make([]string, 0, len(words))
	for w := range words {
		keys = append(keys, w)
	}
	sort.Strings(keys)
	var b bytes.Buffer
	b.WriteString("// Code generated by gen_keywords.go; DO NOT EDIT.\n\n")
	b.WriteString("package sqlident\n\n")
	fmt.Fprintf(&b, "// keywords are the key words that must be quoted as names: the union of\n"+
		"// pg_get_keywords() rows with catcode R, T or C on PostgreSQL %s.\n",
		strings.Join(versions, ", "))
	b.WriteString("var keywords = map[string]byte{\n")
	for _, w := range keys {
		fmt.Fprintf(&b, "%q: '%s',\n", w, words[w])
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
