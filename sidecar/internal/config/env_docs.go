package config

import (
	"fmt"
	"strings"
)

// Markers around the generated environment-variable table in
// docs/configuration.md.
const (
	EnvDocsStart = "<!-- env-vars:start (generated by cmd/gen_config_meta; do not edit) -->"
	EnvDocsEnd   = "<!-- env-vars:end -->"
)

// EnvVarsMarkdown renders the registry as the Markdown table the docs carry.
func EnvVarsMarkdown() string {
	var b strings.Builder
	b.WriteString("| Variable | Default | Description |\n|---|---|---|\n")
	for _, v := range envRegistry {
		name := "`" + v.Name + "`"
		if v.File {
			name += " / `_FILE`"
		}
		fmt.Fprintf(&b, "| %s | %s | %s |\n", name, v.Default, v.Doc)
	}
	return b.String()
}

// envDocsBounds returns the offsets just after the start marker's line and
// at the end marker, or an error naming what is missing.
func envDocsBounds(doc string) (int, int, error) {
	start := strings.Index(doc, EnvDocsStart+"\n")
	end := strings.Index(doc, EnvDocsEnd)
	switch {
	case start < 0:
		return 0, 0, fmt.Errorf("start marker %q not found on its own line", EnvDocsStart)
	case end < 0:
		return 0, 0, fmt.Errorf("end marker %q not found", EnvDocsEnd)
	case end < start:
		return 0, 0, fmt.Errorf("end marker %q comes before the start marker", EnvDocsEnd)
	}
	return start + len(EnvDocsStart) + 1, end, nil
}

// EnvDocsSection returns the text between the markers of doc.
func EnvDocsSection(doc string) (string, error) {
	from, to, err := envDocsBounds(doc)
	if err != nil {
		return "", err
	}
	return doc[from:to], nil
}

// ReplaceEnvDocsSection puts the rendered table between the markers of doc.
func ReplaceEnvDocsSection(doc string) (string, error) {
	from, to, err := envDocsBounds(doc)
	if err != nil {
		return "", err
	}
	return doc[:from] + EnvVarsMarkdown() + doc[to:], nil
}
