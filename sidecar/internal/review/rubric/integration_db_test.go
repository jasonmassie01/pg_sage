// review-01a integration: a fixture database with an int4 key at 80% of
// its sequence, a duplicate index and a table PUBLIC can read without RLS
// gets its grade from the real first look (with its agent posture
// section), the real lint scan and the real settings probe; the expected
// checks fail and none of them passes by being hidden. No concurrent
// access here: the store's concurrency is TestStoreDB_TwoRuns...

func fixtureStatements() []string {
	return []string{
		"DROP SCHEMA IF EXISTS rv_app CASCADE",
		"CREATE SCHEMA rv_app",
		"GRANT USAGE ON SCHEMA rv_app TO PUBLIC",
		`CREATE TABLE rv_app.orders (id int4 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			customer int4 NOT NULL, placed timestamp NOT NULL DEFAULT now())`,
		"SELECT setval(pg_get_serial_sequence('rv_app.orders', 'id'), 1717986918)",
		"CREATE INDEX rv_orders_customer_a ON rv_app.orders (customer)",
		"CREATE INDEX rv_orders_customer_b ON rv_app.orders (customer)",
		"CREATE TABLE rv_app.secrets (id int4 PRIMARY KEY, token text)",
		"GRANT SELECT ON rv_app.secrets TO PUBLIC",
		"ANALYZE rv_app.orders",
	}
}

func statusOf(t *testing.T, g Grade, check string) CheckResult {
	t.Helper()
	for _, d := range g.Dimensions {
		for _, c := range d.Checks {
			if c.Check == check {
				return c
			}
		}
	}
	t.Fatalf("no check %s", check)
	return CheckResult{}
}

func TestIntegrationDB_GradeFromTheRealProducers(t *testing.T) {
	pool, ctx := livePool(t)
	if err := schema.Bootstrap(ctx, pool); err != nil {
		t.Fatalf("second bootstrap: %v", err)
	}
	execAll(t, ctx, pool, fixtureStatements()...)
	t.Cleanup(func() { _, _ = pool.Exec(ctx, "DROP SCHEMA IF EXISTS rv_app CASCADE") })
	report, err := firstlook.Run(ctx, pool, firstlook.Options{Database: "orders"})
	if err != nil {
		t.Fatalf("first look: %v", err)
	}
	if _, err := firstlook.NewStore(pool).Save(ctx, report); err != nil {
		t.Fatalf("save the first look: %v", err)
	}
	lintCfg := config.SchemaLintConfig{MinTableRows: 0}
	loader := &DBLoader{Pool: pool, Database: "orders",
		Lint: lint.New(pool, &lintCfg, 0, func(string, string, ...any) {})}
	run := &Runner{Store: NewStore(pool), Loader: loader, Rubric: V1(), Database: "orders"}
	out, err := run.Run(ctx, KindGrade, []string{"first_look"})
	if err != nil {
		t.Fatalf("grade: %v", err)
	}
	if out.Status != RunDone {
		t.Fatalf("status = %s (%v), want done", out.Status, out.LoadErr)
	}
	for _, check := range []string{"capacity_cost.sequence_runway",
		"schema.duplicate_index", "security_access.rls_exposure"} {
		if c := statusOf(t, out.Grade, check); c.Status != StatusFail || len(c.Evidence) == 0 {
			t.Errorf("%s = %+v, want fail with evidence", check, c)
		}
	}
	assertNothingHiddenPasses(t, out.Grade)
}

// assertNothingHiddenPasses: no drill ran and no analyzer cycle ran on the
// fixture, so those checks are unknown; the lint and settings probes ran.
func assertNothingHiddenPasses(t *testing.T, g Grade) {
	t.Helper()
	for _, check := range []string{"recoverability.restore_drill",
		"workload_stability.query_regression", "recoverability.wal_archive_failing"} {
		if c := statusOf(t, g, check); c.Status != StatusUnknown || c.Reason == "" {
			t.Errorf("%s = %+v, want unknown with a reason", check, c)
		}
	}
	for _, check := range []string{"schema.int_pk", "configuration.pending_restart",
		"lifecycle.server_eol"} {
		if c := statusOf(t, g, check); c.Status == StatusUnknown {
			t.Errorf("%s = %+v, want graded from its real probe", check, c)
		}
	}
	if d := dimOf(t, g, "recoverability"); d.Letter != "" {
		t.Errorf("recoverability = %q without a drill, want unknown", d.Letter)
	}
}
