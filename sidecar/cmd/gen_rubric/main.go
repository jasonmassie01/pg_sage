// Command gen_rubric writes docs/rubric.md (pub-01): Sage Review's
// "well-run Postgres" rubric (review-01a's internal/review/rubric), its
// version, its eight dimensions with every check, what reaches each
// result and each letter, and what reports unknown. It is a build tool,
// not part of the shipped sidecar binary. Run it from sidecar/:
// go run ./cmd/gen_rubric
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/pg-sage/sidecar/internal/review/rubric"
)

const defaultOut = "../docs/rubric.md"

func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, "gen_rubric:", err)
		os.Exit(1)
	}
}

// run writes the page, or with -check fails when the file on disk differs
// from what the rubric gives.
func run(args []string) error {
	fs := flag.NewFlagSet("gen_rubric", flag.ContinueOnError)
	out := fs.String("out", defaultOut, "output path (relative to sidecar/ or absolute)")
	check := fs.Bool("check", false, "write nothing; fail if the file is stale")
	if err := fs.Parse(args); err != nil {
		return err
	}
	doc := Render(rubric.V1())
	if *check {
		raw, err := os.ReadFile(*out)
		if err != nil {
			return fmt.Errorf("read %s: %w", *out, err)
		}
		if strings.ReplaceAll(string(raw), "\r\n", "\n") != doc {
			return fmt.Errorf("%s is stale: run go run ./cmd/gen_rubric", *out)
		}
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(*out), 0o755); err != nil {
		return fmt.Errorf("mkdir %s: %w", filepath.Dir(*out), err)
	}
	if err := os.WriteFile(*out, []byte(doc), 0o644); err != nil {
		return fmt.Errorf("write %s: %w", *out, err)
	}
	return nil
}

// Render is the page's Markdown for r.
func Render(r rubric.Rubric) string {
	var b strings.Builder
	b.WriteString("<!-- generated by cmd/gen_rubric from internal/review/rubric; " +
		"do not edit -->\n")
	b.WriteString("# The pg_sage rubric\n\n")
	fmt.Fprintf(&b, "Rubric version: `%s`. A change to the table below bumps the "+
		"version, and a grade names the version it was computed with.\n\n", r.Version)
	b.WriteString("Licence: this rubric is published under the Creative Commons " +
		"Attribution 4.0 International licence (CC BY 4.0, " +
		"https://creativecommons.org/licenses/by/4.0/). Anyone may grade a database " +
		"with it, by hand or with another tool, and say so. The licence is the " +
		"owner's decision; CC BY 4.0 is the stated default until it is made.\n\n")
	b.WriteString("pg_sage grades a database against this rubric in code, read-only, " +
		"with no model. [Sage Review](review.md) explains the reasoning behind each " +
		"check; this page is generated from the table the code runs.\n\n")
	writeResults(&b)
	writeArithmetic(&b)
	writeSources(&b)
	writeDimensions(&b, r)
	return b.String()
}

func writeResults(b *strings.Builder) {
	b.WriteString("## Check results\n\n")
	b.WriteString("A check that could not run is `unknown`: it stays in the denominator " +
		"and adds nothing, so it can only lower a grade, never raise it.\n\n")
	b.WriteString("| Result | Counts |\n|---|---|\n")
	fmt.Fprintf(b, "| `%s` | its full weight |\n", rubric.StatusPass)
	fmt.Fprintf(b, "| `%s` | %s its weight |\n", rubric.StatusWarn,
		fractionWords(rubric.WarnWeightFraction))
	fmt.Fprintf(b, "| `%s` | nothing |\n", rubric.StatusFail)
	fmt.Fprintf(b, "| `%s` | nothing, and stays in the denominator |\n",
		rubric.StatusUnknown)
	fmt.Fprintf(b, "| `%s` | leaves the denominator; only the platform decides it |\n\n",
		rubric.StatusNotApplicable)
}

func fractionWords(f float64) string {
	if f == 0.5 {
		return "half"
	}
	return fmt.Sprintf("%g of", f)
}

func writeArithmetic(b *strings.Builder) {
	b.WriteString("## Grade arithmetic\n\n")
	b.WriteString("- Dimension score: passed weight over applicable weight, in percent.\n")
	b.WriteString("- Coverage: applicable weight that ran (pass, warn or fail) over " +
		"applicable weight.\n")
	fmt.Fprintf(b, "- A dimension below %g%% coverage has an `unknown` letter; its score "+
		"is still kept.\n", rubric.MinCoveragePct)
	fmt.Fprintf(b, "- A critical check that failed, or could not show that it passed, "+
		"caps its dimension at %s.\n", rubric.CriticalCap)
	b.WriteString("- Overall score: the mean score of every dimension with applicable " +
		"weight, known or not.\n")
	fmt.Fprintf(b, "- Overall letter: `unknown` with fewer than %d dimensions known; "+
		"otherwise the overall score's letter, never more than one letter above the "+
		"worst dimension's.\n\n", rubric.MinKnownDimensions)
	b.WriteString("| Letter | Score from |\n|---|---|\n")
	for _, l := range rubric.Letters() {
		fmt.Fprintf(b, "| %s | %d |\n", l, letterFloor(l))
	}
	b.WriteString("\n")
}

// letterFloor is the lowest whole score rubric.LetterFor gives l.
func letterFloor(l rubric.Letter) int {
	floor := -1
	for score := 100; score >= 0; score-- {
		if rubric.LetterFor(float64(score)) == l {
			floor = score
		}
	}
	return floor
}
