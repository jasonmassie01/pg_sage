// Command gen_finding_catalog writes docs/generated/finding-catalog.md from
// the finding category registry (internal/findingcat): each category's
// subsystem, producer, severities, config keys and the executor contract
// tier of its actions. It is a build tool, not part of the shipped sidecar
// binary. Run it from sidecar/: go run ./cmd/gen_finding_catalog
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/pg-sage/sidecar/internal/executor"
	"github.com/pg-sage/sidecar/internal/findingcat"
)

const defaultOut = "../docs/generated/finding-catalog.md"

func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, "gen_finding_catalog:", err)
		os.Exit(1)
	}
}

// run writes the catalog, or with -check fails when the file on disk
// differs from what the registry renders.
func run(args []string) error {
	fs := flag.NewFlagSet("gen_finding_catalog", flag.ContinueOnError)
	out := fs.String("out", defaultOut, "output path (relative to sidecar/ or absolute)")
	check := fs.Bool("check", false, "write nothing; fail if the file is stale")
	if err := fs.Parse(args); err != nil {
		return err
	}
	doc, err := Render()
	if err != nil {
		return err
	}
	if *check {
		raw, err := os.ReadFile(*out)
		if err != nil {
			return fmt.Errorf("read %s: %w", *out, err)
		}
		if strings.ReplaceAll(string(raw), "\r\n", "\n") != doc {
			return fmt.Errorf("%s is stale: run go run ./cmd/gen_finding_catalog", *out)
		}
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(*out), 0o755); err != nil {
		return fmt.Errorf("mkdir %s: %w", filepath.Dir(*out), err)
	}
	if err := os.WriteFile(*out, []byte(doc), 0o644); err != nil {
		return fmt.Errorf("write %s: %w", *out, err)
	}
	return nil
}

// Anchor is a category's section anchor in docs/findings.md: its name,
// without the colon a prefix family ends in.
func Anchor(c findingcat.Category) string {
	return strings.TrimSuffix(c.Name, ":")
}

// contractTier is an action's executor contract base risk tier, or ""
// when the action has no contract.
func contractTier(action string) string {
	c, ok := executor.ContractForActionType(action)
	if !ok {
		return ""
	}
	return c.BaseRiskTier
}

// Render returns the catalog Markdown, one table per subsystem.
func Render() (string, error) {
	var b bytes.Buffer
	all := findingcat.All()
	b.WriteString("# Finding category catalog\n\n")
	b.WriteString("<!-- Generated by `go run ./cmd/gen_finding_catalog` from " +
		"sidecar/internal/findingcat. Do not edit by hand. -->\n\n")
	fmt.Fprintf(&b, "%d categories and prefix families in %d subsystems. The subsystem "+
		"is the `source` value of `GET /api/v1/findings` that shows the category, and "+
		"`GET /api/v1/findings/categories` serves this registry. Descriptions are in "+
		"[the findings catalog](../findings.md).\n\n", len(all), len(findingcat.Subsystems()))
	b.WriteString("Actions are the executor action types the category's SQL can run as, " +
		"with the base risk tier of their contract; a category without one is advisory.\n")
	for _, s := range findingcat.Subsystems() {
		fmt.Fprintf(&b, "\n## %s\n\n", s)
		b.WriteString("| Category | Producer | Severities | Config keys | Actions | Summary |\n")
		b.WriteString("|---|---|---|---|---|---|\n")
		for _, c := range all {
			if c.Subsystem != s {
				continue
			}
			row, err := renderRow(c)
			if err != nil {
				return "", err
			}
			b.WriteString(row)
		}
	}
	return b.String(), nil
}

// renderRow is one category's table row; an action without a contract
// is an error, so the catalog never shows a tier it cannot back.
func renderRow(c findingcat.Category) (string, error) {
	name := c.Name
	if c.Prefix {
		name += "*"
	}
	actions := make([]string, 0, len(c.Actions))
	for _, a := range c.Actions {
		tier := contractTier(a)
		if tier == "" {
			return "", fmt.Errorf("category %q: action %q has no executor contract", c.Name, a)
		}
		actions = append(actions, fmt.Sprintf("`%s` (%s)", a, tier))
	}
	summary := c.Summary
	if len(c.AlsoIn) > 0 {
		summary = fmt.Sprintf("%s; also shown under %s.", strings.TrimSuffix(summary, "."),
			codeList(c.AlsoIn))
	}
	return fmt.Sprintf("| [`%s`](../findings.md#%s) | %s | %s | %s | %s | %s |\n",
		name, Anchor(c), c.Producer, strings.Join(c.Severities, ", "),
		codeList(c.ConfigKeys), dashIfEmpty(strings.Join(actions, ", ")), summary), nil
}

func codeList(items []string) string {
	if len(items) == 0 {
		return "-"
	}
	return "`" + strings.Join(items, "`, `") + "`"
}

func dashIfEmpty(s string) string {
	if s == "" {
		return "-"
	}
	return s
}
