// Command gen_verifier_backtest writes docs/generated/verifier-backtest.md
// (lab-02): the verifier back-test on each of the five bench fixtures of
// internal/verify/backtest, v2's placebo false-positive rate with its
// Wilson 95% upper bound, the inconclusive share and the detection rate,
// beside v1's on the same placebos. It is a build tool, not part of the
// shipped sidecar binary. Run it from sidecar/: go run ./cmd/gen_verifier_backtest
package main

import (
	"context"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"

	"github.com/pg-sage/sidecar/internal/verify/backtest"
)

const defaultOut = "../docs/generated/verifier-backtest.md"

// seed is the placebo draw's seed of the published numbers.
const seed = 1

func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, "gen_verifier_backtest:", err)
		os.Exit(1)
	}
}

// run writes the page, or with -check fails when the file on disk differs
// from what the fixtures give.
func run(args []string) error {
	fs := flag.NewFlagSet("gen_verifier_backtest", flag.ContinueOnError)
	out := fs.String("out", defaultOut, "output path (relative to sidecar/ or absolute)")
	check := fs.Bool("check", false, "write nothing; fail if the file is stale")
	if err := fs.Parse(args); err != nil {
		return err
	}
	doc, err := Render(context.Background())
	if err != nil {
		return err
	}
	if *check {
		raw, err := os.ReadFile(*out)
		if err != nil {
			return fmt.Errorf("read %s: %w", *out, err)
		}
		if strings.ReplaceAll(string(raw), "\r\n", "\n") != doc {
			return fmt.Errorf("%s is stale: run go run ./cmd/gen_verifier_backtest", *out)
		}
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(*out), 0o755); err != nil {
		return fmt.Errorf("mkdir %s: %w", filepath.Dir(*out), err)
	}
	if err := os.WriteFile(*out, []byte(doc), 0o644); err != nil {
		return fmt.Errorf("write %s: %w", *out, err)
	}
	return nil
}

// Results back-tests every fixture with the published seed.
func Results(ctx context.Context) (map[string]backtest.Result, error) {
	end := backtest.FixtureStart.Add(backtest.FixtureDays * 24 * time.Hour)
	out := map[string]backtest.Result{}
	for _, name := range backtest.FixtureNames {
		m, err := backtest.Fixture(name)
		if err != nil {
			return nil, err
		}
		r, err := backtest.Run(ctx, m, backtest.Config{Database: name,
			Days: backtest.DefaultDays, Placebos: backtest.DefaultPlacebos, Seed: seed,
			MaxRuntime: time.Hour, Cycle: backtest.FixtureCycle,
			Now: func() time.Time { return end }})
		if err != nil {
			return nil, fmt.Errorf("back-test fixture %s: %w", name, err)
		}
		out[name] = r
	}
	return out, nil
}

// Render is the page's Markdown.
func Render(ctx context.Context) (string, error) {
	results, err := Results(ctx)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString("<!-- generated by cmd/gen_verifier_backtest; do not edit -->\n")
	b.WriteString("# Verifier back-test on the bench fixtures\n\n")
	fmt.Fprintf(&b, "Each fixture is %d days of synthetic history with no real step "+
		"in it. %d placebo steps (seed %d) are replayed through verification v2 and, "+
		"for comparison, v1; the same placebos with a synthetic 30%% drop in blocks "+
		"per call give the detection rate. See docs/verification.md for the method.\n\n",
		backtest.FixtureDays, backtest.DefaultPlacebos, seed)
	b.WriteString(backtest.FixtureTable(results))
	b.WriteString("\nThe gate verify.method auto reads needs at least 200 usable placebos, " +
		"a false-positive rate at or below 5% and a detection rate at or above 80%:\n\n")
	for _, name := range backtest.FixtureNames {
		ok, reason := results[name].Gate()
		verdict := "passes"
		if !ok {
			verdict = "refused: " + reason
		}
		fmt.Fprintf(&b, "- `%s`: %s\n", name, verdict)
	}
	return b.String(), nil
}
